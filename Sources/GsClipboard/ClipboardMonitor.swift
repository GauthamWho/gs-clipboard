import AppKit

@MainActor
final class ClipboardMonitor {
    private let store: ClipStore
    private var timer: Timer?
    private var lastChangeCount: Int
    var ignoreNextChange = false

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Diag.log("monitor started (changeCount=\(lastChangeCount))")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if ignoreNextChange {
            ignoreNextChange = false
            Diag.log("skipped change \(count) (written by us)")
            return
        }
        capture(pasteboard, changeCount: count)
    }

    private func capture(_ pasteboard: NSPasteboard, changeCount: Int) {
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        let types = pasteboard.types?.map(\.rawValue).joined(separator: ",") ?? "none"

        // Password managers and apps mark secret or throwaway copies; those are never saved.
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                    "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
                    "com.typeit4me.clipping", "net.antelle.keeweb"]
        if let raw = pasteboard.types?.map(\.rawValue), raw.contains(where: skip.contains) {
            Diag.log("change=\(changeCount) skipped: marked private by \(source ?? "?")")
            return
        }

        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let image = NSImage(data: data),
           let png = image.pngData() {
            store.addImage(png: png, source: source)
            Diag.log("captured image change=\(changeCount) from=\(source ?? "?")")
            return
        }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls, source: source)
            Diag.log("captured \(urls.count) file(s) change=\(changeCount)")
            return
        }

        if let text = plainText(from: pasteboard), !text.isEmpty {
            store.addText(text, source: source)
            Diag.log("captured text change=\(changeCount) len=\(text.count) from=\(source ?? "?")")
            return
        }

        Diag.log("change=\(changeCount) had no usable content (types: \(types))")
    }

    /// Some apps copy rich content without a plain-string flavour. Fall back to
    /// HTML then RTF and strip the markup so the text is still saved.
    private func plainText(from pasteboard: NSPasteboard) -> String? {
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return text
        }


        if let rtf = pasteboard.data(forType: .rtf),
           let attributed = try? NSAttributedString(
                data: rtf,
                options: [.documentType: NSAttributedString.DocumentType.rtf],
                documentAttributes: nil),
           !attributed.string.isEmpty {
            return attributed.string
        }

        // HTML last, stripped as plain text. The system HTML importer is never used, because it
        // can load remote images and stylesheets.
        if let html = pasteboard.data(forType: .html).flatMap({ String(data: $0, encoding: .utf8) }) {
            let text = Self.stripHTML(html)
            if !text.isEmpty { return text }
        }

        return nil
    }

    static func stripHTML(_ html: String) -> String {
        var s = html.replacingOccurrences(of: "(?is)<(script|style|head)[^>]*>.*?</\\1>", with: "", options: .regularExpression)
        s = s.replacingOccurrences(of: "(?i)<br\\s*/?>|</(p|div|li|tr|h[1-6])>", with: "\n", options: .regularExpression)
        s = s.replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
        for (e, c) in [("&nbsp;", " "), ("&lt;", "<"), ("&gt;", ">"), ("&quot;", "\""), ("&#39;", "'"), ("&apos;", "'"), ("&amp;", "&")] {
            s = s.replacingOccurrences(of: e, with: c)
        }
        return s.replacingOccurrences(of: "\n{3,}", with: "\n\n", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
